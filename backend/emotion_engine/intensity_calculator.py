def calculate_intensity(emotion_scores):
    """
    Calculates the emotional intensity of a story
    using the emotion scores generated by
    emotion_classifier.py.
    """

    # Calculate the total emotional score
    total_score = sum(emotion_scores.values())

    # Normalize the total score to a maximum of 10
    intensity_score = min(total_score, 10)

    # Assign an intensity level
    if intensity_score == 0:
        intensity_level = "None"

    elif intensity_score <= 2:
        intensity_level = "Very Low"

    elif intensity_score <= 4:
        intensity_level = "Low"

    elif intensity_score <= 6:
        intensity_level = "Medium"

    elif intensity_score <= 8:
        intensity_level = "High"

    else:
        intensity_level = "Extreme"

    # Return the final intensity report
    return {
        "intensity_score": intensity_score,
        "intensity_level": intensity_level
    }